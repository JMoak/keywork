import type { MemoryQuestion } from "../../packages/engine/src/index.ts";
import type { ArmSource } from "./arms.ts";
import { type Corpus, corpusDigest, type DecisionPoint } from "./corpus.ts";
import { dollars, fixed, grouped, percent, plural } from "./format.ts";
import { gateQuestion, passedCount, type QuestionVerdict } from "./gate.ts";
import {
  type Answers,
  answersOf,
  disagreements,
  isActionQuestion,
  isHotPathQuestion,
  measureQuestion,
  type QuestionMeasures,
  questionsIn,
  type RecallQuality,
} from "./metrics.ts";
import { builtinEdition, editionName, offEdition } from "./replay.ts";
import type { Run } from "./runs.ts";

export interface ReportInput {
  corpus: Corpus;
  corpusName: string;
  run: Run;
  builtin: Answers;
  off: Answers;
}

export const verdictHeading = "## Verdict";

export function formatReport(input: ReportInput): string {
  const sections =
    input.run.record.skipped === undefined
      ? answeredSections(input, answersOf(input.run.answers))
      : skippedSections(input, input.run.record.skipped);
  return `${sections.join("\n\n")}\n`;
}

const builtinName = editionName(builtinEdition);
const offName = editionName(offEdition);

interface Arm {
  name: string;
  measures: QuestionMeasures;
  answers: Answers;
}

function answeredSections(input: ReportInput, answers: Answers): string[] {
  const name = editionName(input.run.record.edition);
  const reference = name === builtinName;
  const measured = questionsIn(input.corpus).map((question) => {
    const arms = armsFor(question, input, answers, reference);
    const verdict = reference ? undefined : gateQuestion(arms[0].measures, arms[1].measures);
    return { question, arms, verdict };
  });
  return [
    `# Memory eval: ${name}`,
    introduction(input, reference),
    judgeNote(input.corpus),
    verdictTable(
      measured.map(({ question, arms, verdict }) => verdictRow(question, arms, verdict)),
    ),
    ...measured.flatMap(({ question, arms, verdict }) =>
      questionSection(question, input, arms, verdict),
    ),
  ];
}

function skippedSections(input: ReportInput, reason: string): string[] {
  const { edition } = input.run.record;
  const heldOut = (question: MemoryQuestion) =>
    input.corpus.points.filter((point) => point.question === question && point.half === "held-out")
      .length;
  return [
    `# Memory eval: ${editionName(edition)}`,
    `Decider \`${edition.decider}\` version \`${edition.version}\` over \`${input.corpusName}\` was not run, so it proves nothing. Skipped: ${reason}.`,
    verdictTable(
      questionsIn(input.corpus).map(
        (question) => `| \`${question}\` | ${heldOut(question)} | not run | no |`,
      ),
    ),
  ];
}

type Arms = [Arm, Arm, ...Arm[]];

function armsFor(
  question: MemoryQuestion,
  input: ReportInput,
  answers: Answers,
  reference: boolean,
): Arms {
  const builtin: Arm = {
    name: builtinName,
    answers: input.builtin,
    measures: measureQuestion(question, input.corpus, input.builtin),
  };
  const off: Arm = {
    name: `${offName} (floor)`,
    answers: input.off,
    measures: measureQuestion(question, input.corpus, input.off, input.builtin),
  };
  if (reference) return [builtin, off];
  const challenger: Arm = {
    name: editionName(input.run.record.edition),
    answers,
    measures: measureQuestion(question, input.corpus, answers, input.builtin),
  };
  return [challenger, builtin, off];
}

function introduction(input: ReportInput, reference: boolean): string {
  const { record } = input.run;
  const { points } = input.corpus;
  const heldOut = points.filter((point) => point.half === "held-out").length;
  const opening = `Decider \`${record.edition.decider}\` version \`${record.edition.version}\`, ${sourceWords(record.source)}, over \`${input.corpusName}\`: ${points.length} decision points (corpus \`${corpusDigest(points)}\`), ${heldOut} held out for the gate and ${points.length - heldOut} kept to fit calibration maps.`;
  const role = reference
    ? "This is the reference arm: every challenger's gate is measured against these numbers, so this report proves no question by itself."
    : `The gate (121, decision 10) compares it with ${builtinName} on the held-out half. A question proven here joins \`memoryEvalProofs\` in \`packages/engine/src/memory/proven-questions.ts\` in the change that checks this report in.`;
  return `${opening} ${role} Generated by \`bun run memory:eval report\`; regenerate it rather than editing it.`;
}

function sourceWords(source: ArmSource | undefined): string {
  switch (source) {
    case "cassette":
      return "answers replayed from its cassette";
    case "live":
      return "answers recorded live";
    default:
      return "answering by its rules";
  }
}

function judgeNote(corpus: Corpus): string {
  const judge = corpus.manifest?.judge;
  const judged =
    judge === undefined
      ? "Judge labels: none, because the corpus has no harvest manifest."
      : judge.ran
        ? `Judge labels: ${judge.labels} from \`${judge.judge}\`, the person's own chat model.`
        : `Judge labels: none, because the harvest ran without a judge (${judge.reason}).`;
  return `${judged} Answer quality (the next turn re-run with each arm's injection and compared blind by the judge) runs on demand and was not run for this report.`;
}

function verdictTable(rows: readonly string[]): string {
  return [
    verdictHeading,
    "",
    "| Question | Held-out points | Gate | Proven |",
    "|---|---|---|---|",
    ...rows,
  ].join("\n");
}

function verdictRow(
  question: MemoryQuestion,
  arms: Arms,
  verdict: QuestionVerdict | undefined,
): string {
  const heldOut = arms[0].measures.points;
  if (verdict === undefined) return `| \`${question}\` | ${heldOut} | reference arm | reference |`;
  const gate = `${passedCount(verdict)} of ${verdict.criteria.length} criteria pass`;
  return `| \`${question}\` | ${heldOut} | ${gate} | ${verdict.proven ? "yes" : "no"} |`;
}

function questionSection(
  question: MemoryQuestion,
  input: ReportInput,
  arms: Arms,
  verdict: QuestionVerdict | undefined,
): string[] {
  const [first, second] = arms;
  const points = input.corpus.points.filter(
    (point) => point.question === question && point.half === "held-out",
  );
  return [
    `## \`${question}\``,
    measureTable(question, arms, input.corpus),
    ...(verdict === undefined
      ? []
      : [gateTable(verdict), ...harmfulDrops(first.measures), ...calibrationMap(first.measures)]),
    disagreementList(points, first, second),
  ];
}

function measureTable(question: MemoryQuestion, arms: Arms, corpus: Corpus): string {
  const header = `| Measure | ${arms.map((arm) => arm.name).join(" | ")} |`;
  const rule = `|---|${arms.map(() => "---").join("|")}|`;
  const rows = measureRows(question, corpus).map(
    ([label, cell]) =>
      `| ${label} | ${arms.map((arm, index) => cell(arm.measures, index)).join(" | ")} |`,
  );
  return [header, rule, ...rows].join("\n");
}

type MeasureRow = [string, (measures: QuestionMeasures, column: number) => string];

function measureRows(question: MemoryQuestion, corpus: Corpus): MeasureRow[] {
  const shared: MeasureRow[] = [
    ["Latency p50 / p95", (m) => `${m.latency.p50} / ${m.latency.p95} ms`],
    ...(isHotPathQuestion(question)
      ? [
          [
            "Hot-path wait p50 / p95 / max",
            (m: QuestionMeasures) =>
              `${m.waited?.p50 ?? 0} / ${m.waited?.p95 ?? 0} / ${m.waited?.max ?? 0} ms`,
          ] as MeasureRow,
        ]
      : []),
    ["Fallbacks", fallbackCell],
    ["Calibration (ECE after the map)", calibrationCell],
    ["Complement probe", () => "not run: the port asks no negated question"],
    ["Cost", (m) => `${dollars(m.cost.usd)} (${grouped(m.cost.inputTokens)} decider input tokens)`],
  ];
  if (!isActionQuestion(question))
    return [
      ["Decision points (held out)", (m) => String(m.points)],
      ["Agreement with the person's verdicts", agreementCell],
      ...shared,
    ];
  const judged = corpus.labels.some((label) => label.source === "judge");
  return [
    ["Decision points (held out)", (m) => String(m.points)],
    ["Tokens injected", injectedCell],
    ["Tokens carried (injected × turns ridden)", (m) => grouped(m.injection?.carried ?? 0)],
    ["Hindsight recall", (m) => recallCell(m.hindsight)],
    ["Hindsight precision", (m) => precisionCell(m.hindsight)],
    ["Judge-rated recall", (m) => (judged ? recallCell(m.judged) : "skipped: no judge labels")],
    [
      "Judge-rated precision",
      (m) => (judged ? precisionCell(m.judged) : "skipped: no judge labels"),
    ],
    ["Harmful drops", (m, column) => harmfulCell(m, column)],
    ["Answer quality", () => "not run (on demand)"],
    ...shared,
  ];
}

function injectedCell(measures: QuestionMeasures): string {
  const injected = measures.injection?.injected ?? 0;
  const perPoint = measures.points === 0 ? 0 : injected / measures.points;
  return `${grouped(injected)} (${fixed(perPoint, 1)} per point)`;
}

function recallCell(quality: RecallQuality | undefined): string {
  if (quality?.recall === undefined) return "n/a: nothing relevant labeled";
  return `${fixed(quality.recall)} (${quality.keptRelevant} of ${quality.relevant} relevant)`;
}

function precisionCell(quality: RecallQuality | undefined): string {
  if (quality?.precision === undefined) return "n/a: kept nothing labeled";
  return `${fixed(quality.precision)} (${quality.keptRelevant} of ${quality.kept} kept)`;
}

function harmfulCell(measures: QuestionMeasures, column: number): string {
  const harmful = (measures.judged ?? measures.hindsight)?.harmful;
  if (harmful === undefined) return column === 0 ? "n/a: the baseline itself" : "n/a: the baseline";
  return `${harmful.count} (${percent(harmful.rate)} of relevant)`;
}

function agreementCell(measures: QuestionMeasures): string {
  const agreement = measures.agreement;
  if (agreement?.rate === undefined) return "n/a: no labeled verdicts";
  return `${fixed(agreement.rate)} (${agreement.agreed} of ${agreement.labeled} labeled)`;
}

function fallbackCell(measures: QuestionMeasures): string {
  if (measures.fallbacks.length === 0) return "none";
  return measures.fallbacks.map(({ reason, count }) => `${reason} ${count}`).join(", ");
}

function calibrationCell(measures: QuestionMeasures): string {
  const calibration = measures.calibration;
  if (calibration === undefined) return "n/a: states no labeled probabilities";
  return `${fixed(calibration.ece, 3)} (raw ${fixed(calibration.rawEce, 3)}, noise floor ${fixed(calibration.noiseFloor, 3)}, ${plural(calibration.samples, "sample")})`;
}

function gateTable(verdict: QuestionVerdict): string {
  return [
    "| Criterion | Result | Measured |",
    "|---|---|---|",
    ...verdict.criteria.map(
      (criterion) =>
        `| ${criterion.number}. ${criterion.name} | ${criterion.passed ? "pass" : "fail"} | ${criterion.detail} |`,
    ),
  ].join("\n");
}

function harmfulDrops(measures: QuestionMeasures): string[] {
  const drops = (measures.judged ?? measures.hindsight)?.harmful?.drops;
  if (drops === undefined) return [];
  if (drops.length === 0) return ["Harmful drops: none."];
  const listed = drops.map((drop) => `- \`${drop.point}\` dropped [[${drop.note}]]`);
  return [["Harmful drops:", "", ...listed].join("\n")];
}

function calibrationMap(measures: QuestionMeasures): string[] {
  const map = measures.calibration?.map ?? [];
  if (map.length === 0) return [];
  return [
    [
      "Fitted calibration map (stated probability up to, calibrated):",
      "",
      "| Stated up to | Calibrated |",
      "|---|---|",
      ...map.map((step) => `| ${fixed(step.upTo, 3)} | ${fixed(step.calibrated, 3)} |`),
    ].join("\n"),
  ];
}

function disagreementList(points: readonly DecisionPoint[], ours: Arm, theirs: Arm): string {
  const found = disagreements(points, ours.answers, theirs.answers);
  const heading = `Disagreements between ${ours.name} and ${theirs.name}: ${found.length}.`;
  if (found.length === 0) return heading;
  return [
    heading,
    "",
    ...found.map(
      (entry) =>
        `- \`${entry.point}\` ${entry.subject}: ${ours.name} ${entry.ours}; ${theirs.name} ${entry.theirs}`,
    ),
  ].join("\n");
}
